/** Generates docs/AUTH-METHODS.md from the same diagrams the web app renders (single source of truth). */
import { writeFileSync } from 'node:fs';
import { AUTH_METHODS } from '../libs/shared/src/index';
import { CONTENT, OVERVIEW_DIAGRAMS } from '../apps/web/src/content';

const md: string[] = ['# AuthLab – Authentication methods reference', '', '> Generated by `npm run docs` from `apps/web/src/content.ts`. GitHub renders the Mermaid blocks.', ''];
md.push('## Overview', '');
for (const d of OVERVIEW_DIAGRAMS) md.push(`### ${d.title}`, '', '```mermaid', d.code, '```', '');
md.push('## Contents', '', ...AUTH_METHODS.map((m, i) => `${i + 1}. [${m.title}](#${m.id}) – *${m.category}*`), '');
AUTH_METHODS.forEach((m, i) => {
  const c = CONTENT[m.id]!;
  md.push(`<a id="${m.id}"></a>`, `## ${i + 1}. ${m.title}`, '', `**Kind:** ${m.category} · **Answers:** ${m.answers.join(', ')} · **${m.stateful ? 'Stateful' : 'Stateless'}** · **API:** \`${m.apiBase}\``, '', c.summary, '',
    `| Credential travels as | Best for | Avoid when |`, `|---|---|---|`, `| \`${m.credentialIn}\` | ${m.bestFor} | ${m.avoidWhen} |`, '');
  for (const d of c.diagrams) md.push(`### ${d.title}`, '', '```mermaid', d.code, '```', '');
  md.push('**Standard practices implemented**', '', ...c.practices.map((p) => `- ✅ ${p}`), '', '**Pitfalls**', '', ...c.pitfalls.map((p) => `- ⚠️ ${p}`), '', '```bash', c.curl, '```', '');
});
writeFileSync(new URL('../docs/AUTH-METHODS.md', import.meta.url), md.join('\n'));
console.log('docs/AUTH-METHODS.md written');
